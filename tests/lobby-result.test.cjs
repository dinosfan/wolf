'use strict';
const assert=require('assert'),vm=require('vm');const {harness}=require('./simulation-harness.cjs');
const h=harness(),host=h.client(),guest=h.client(),third=h.client();
const code=host.call('room:create',{name:'Host'}).code;
const joined=guest.call('room:join',{code,name:'Guest'});third.call('room:join',{code,name:'Third'});
const room=h.room(code);
host.call('room:setDiscussion',{seconds:420});assert.equal(room.discussionSeconds,420);
guest.call('room:setDiscussion',{seconds:60});assert.equal(room.discussionSeconds,420,'Only host changes the time');
const roles=['werewolf','werewolf','seer','robber','troublemaker','villager'];host.call('room:setRoles',{roles});host.call('game:start');
assert(!guest.call('room:leave').ok,'Cannot leave during an active round');
h.ctx.r=room;vm.runInContext('beginDiscussion(r)',h.ctx);assert.equal(room.discussionEndsAt-h.now(),420000);
host.call('room:setDiscussion',{seconds:60});assert.equal(room.discussionSeconds,420,'Time set before game remains fixed during play');
host.call('discussion:endEarly');host.call('vote:cast',{targetId:guest.id});guest.call('vote:cast',{targetId:third.id});third.call('vote:cast',{targetId:host.id});assert.equal(room.phase,'result');
const result=JSON.stringify(room.lastReveal);
assert(guest.call('room:leave').ok,'Guest can leave directly from the result');assert.equal(room.players.length,2);assert.equal(JSON.stringify(room.lastReveal),result,'Other players retain the complete round result');
assert(!h.client().call('room:resume',{code,resumeToken:joined.resumeToken}).ok,'Leaving clears membership');
assert(host.call('room:leave').ok);assert.equal(room.hostId,third.id,'Leaving host passes ownership');
third.call('game:restart');assert.equal(room.phase,'lobby');assert.equal(room.discussionSeconds,420);
assert(third.call('room:leave').ok);assert(!h.room(code));
console.log('Result exit and pregame discussion time checks passed.');
